// Hearthwood - class RESOURCE PROFILES (Mana & Skill Resource PRD, step 2).
// One universal resource engine (services/heartwood/tacticsMana.js) runs
// every profile below; a class picks its profile with `resource` in
// classes.js. Pure data - Studio-editable (Hearthwood Studio > Resources).
//
// "Give every class a unique relationship with power." (Marc, PRD §70)
//
// Profile fields (all numbers are per TURN in this turn-based game):
//   name / short / icon / color  - what the player sees ("Rage", "20 Rage")
//   gauge   - how the meter looks under the HP bar:
//             bar | pips | counter | wheel | tokens | reserve | tiers
//   max     - the cap (0 = the class's own `manaPool`, classic mana)
//   startPct      - a hero starts each fight at this % of max (0 = empty)
//   enemyStartPct - same for enemies that use this profile
//   regen / regenPct - gained at the start of each own turn (flat / % of max)
//   decay   - lost at the start of each own turn ...
//   decayWhen - "always", or "idle" (only if it neither hit nor was hit
//             since its last turn - "cools down when not fighting")
//   overflow  - true: anything above max is stored as Overcharge
//   costScale - converts a signature ability's mana price into this
//             resource (class skills carry their own price in classes.js)
//   gain    - how the resource is BUILT (see GAIN_TEXT for what each key means)
//   breakpoints - 25/50/75/100% of max: every reached step adds its bonus
//             (dmg = +damage per hit, aim = +% to hit, heal = +healing,
//             guard = takes less per hit, taken = takes more per hit,
//             skillPct = +% skill damage, cheaper = % cheaper skills,
//             empower = the next skill is Empowered (+50%),
//             berserk = enter Berserk, grand = next skill sets off a Grand Curse)
//   special - the profile's own rule (tiers / states / reserve / tokens /
//             inverted / sacrifice / souls / berserk / grandCurse)
//   text    - the plain-English rules (tooltips, Studio)

