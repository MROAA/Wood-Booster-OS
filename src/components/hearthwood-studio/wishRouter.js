// Search words for the entity lookup: longer words, Finnish case endings
// trimmed ("Tommyn" -> "tommy", "Mauralle" -> "maura").
export function searchWords(text) {
  const words = String(text).toLowerCase().match(/[a-zåäö0-9'-]{4,}/g) || []
  const out = []
  for (const word of words) {
    if (STOP.has(word)) continue
    const bare = word.replace(/(lle|lla|llä|lta|ltä|ssa|ssä|sta|stä|ksi|n|a|ä)$/, "")
    for (const w of [word, bare]) if (w.length >= 4 && !out.includes(w)) out.push(w)
  }
  return out.slice(0, 6)
}

// The best entity match among /search results for those words.
export function bestMatch(words, results) {
  let best = null
  for (const result of results || []) {
    const name = String(result.name || result.id).toLowerCase()
    const id = String(result.id).toLowerCase()
    for (const word of words) {
      if (!name.includes(word) && !id.includes(word)) continue
      const score = (name === word || id === word ? 3 : name.startsWith(word) ? 2 : 1) + word.length / 100
      if (!best || score > best.score) best = { ...result, score }
    }
  }
  return best
}

export function routeWish(text, searchResults = []) {
  const raw = String(text || "").trim()
  const t = ` ${raw.toLowerCase()} `
  if (!raw) return { kind: "unclear", reason: "Write what you'd like to make or change." }
  const found = bestMatch(searchWords(raw), searchResults)
  const creating = has(t, NEW) || (has(t, MAKE) && !found)
  const changing = has(t, CHANGE) || (has(t, MAKE) && !!found)

  if (has(t, COLOURS) && !found) return { kind: "view", view: "theme", label: "Look & Colours", why: "Colours, fonts and spacing are changed in Look & Colours, with a preview before anything is kept." }

  if (has(t, PICTURE) && found) return { kind: "open", entity: found, why: `The picture of ${found.name || found.id} is the first thing on its page - press "Choose image".` }

  if (creating) {
    const form = ADD_FORMS.find(f => has(t, f.words))
    if (form) return { kind: "add", type: form.type, why: `The Studio has a form for ${form.label}.` }
    const blocked = NEEDS_CODE.find(n => has(t, n.words))
    if (blocked) return { kind: "needsCode", what: blocked.what, today: blocked.today }
    const clone = CLONE_FORMS.find(f => has(t, f.words))
    if (clone) return { kind: "clone", type: clone.type, why: `You can make ${clone.label}: change its name, numbers and picture, then Apply.` }
  }

  if (found && (changing || !creating)) {
    return changing
      ? { kind: "change", entity: found, why: `This is a change to ${found.name || found.id}. The AI prepares it for you to check - nothing is saved before you press "Put it in the game".` }
      : { kind: "open", entity: found, why: `Found ${found.name || found.id}.` }
  }

  const blocked = NEEDS_CODE.find(n => has(t, n.words))
  if (blocked && (creating || changing)) return { kind: "needsCode", what: blocked.what, today: blocked.today }
  if (creating) return { kind: "needsCode", what: "this", today: "The Studio couldn't match it to anything it can make yet." }
  return { kind: "unclear", reason: "I couldn't tell what you mean. Try naming the thing, e.g. \"change Tommy's picture\" or \"make a new map event\"." }
}
